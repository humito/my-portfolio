#include "CInput.h"
//=============================================================================
//コンストラクタ
//=============================================================================
CInput::CInput()
{
	m_pDInput=NULL;
}
//=============================================================================
//デストラクタ
//=============================================================================
CInput::~CInput()
{
}
//=============================================================================
//入力処理初期化
//=============================================================================
HRESULT CInput::Init(HINSTANCE hInstance, HWND hWnd)
{
	// DirectInputオブジェクトの作成
	if(m_pDInput==NULL)
	{
		hr=DirectInput8Create(hInstance,DIRECTINPUT_VERSION,
							  IID_IDirectInput8,(void**)&m_pDInput,
							  NULL);
		if(FAILED(hr))
		{
			return hr;
		}
	}
	return S_OK;
}
//=============================================================================
//入力処理終了
//=============================================================================
void CInput::Uninit()
{
	// DirectInputオブジェクトの開放
	if(m_pDInput!=NULL)
	{
		m_pDInput->Release();
		m_pDInput=NULL;
	}

}
