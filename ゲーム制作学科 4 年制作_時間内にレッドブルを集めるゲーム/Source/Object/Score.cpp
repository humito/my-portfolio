#include "Score.h"
#include "../manager.h"
#include "../System/renderer.h"

//*****************************************************************************
//定数定義
//*****************************************************************************
#define SCORE_NUM_MAX	(99)	//スコア最大値

//*****************************************************************************
//スタティックメンバ変数
//*****************************************************************************
int CScore::m_nScore = 0;//スコア値

//=============================================================================
//初期化
//=============================================================================
HRESULT CScore::Init(D3DXVECTOR3 pos, float fWidth, float fHeight, int mode, NUMBER_DISP type, int nDigitNum)
{
	//スコアモード
	m_nScoreMode = mode;

	//数値の初期化
	m_Number.Init("data/TEXTURE/number001.png", pos, type,
					fWidth, fHeight, nDigitNum);

	return S_OK;
}
//=============================================================================
//終了
//=============================================================================
void CScore::Uninit()
{
	//数値の終了
	m_Number.Uninit();

	//自身の終了
	this->Release();
}
//=============================================================================
//更新
//=============================================================================
void CScore::Update()
{
	//スコアが最大値より上に達したら最大値にする
	if (m_nScore>SCORE_NUM_MAX)
	{
		m_nScore = SCORE_NUM_MAX;
	}

	//スコアを数値に代入して１桁ずつ抽出させる
	m_Number.SetValue(m_nScore);
}
//=============================================================================
//描画
//=============================================================================
void CScore::Draw()
{
	//数値の描画
	m_Number.Draw();
}
//=============================================================================
//スコア値加算
//=============================================================================
void CScore::AddScore(int num)
{
	//スコアの加算
	m_nScore += num;
}
//=============================================================================
//スコアのセット
//=============================================================================
void CScore::SetScore(int num)
{
	m_nScore = num;
}
//=============================================================================
//スコアインスタンス生成
//=============================================================================
void CScore::Create(D3DXVECTOR3 pos, float fWidth, float fHeight, int mode, NUMBER_DISP type, int nDigitNum)
{
	//スコアインスタンス生成
	CScore *pScore = new CScore();

	//初期化
	pScore->Init(pos, fWidth, fHeight, mode, type, nDigitNum);
}
