#include "Shader.h"

//=============================================================================
//コンストラクタ
//=============================================================================
CShader::CShader()
{
	m_pEffect = NULL;
	m_pTechnique = NULL;
}
//=============================================================================
//デストラクタ
//=============================================================================
CShader::~CShader()
{
	//エフェクト解放
	if (m_pEffect)
	{
		m_pEffect->Release();
		m_pEffect = NULL;
	}
}
//=============================================================================
//復元
//=============================================================================
void CShader::Restore()
{
	if (m_pEffect)
	{
		m_pEffect->OnResetDevice();
	}
}
//=============================================================================
//ステート変更
//=============================================================================
void CShader::CommitChanges()
{
	if (m_pEffect)
	{
		m_pEffect->CommitChanges();
	}
}
//=============================================================================
//エフェクト使用可能かチェック
//=============================================================================
bool CShader::IsOK()
{
	if (m_pEffect)
	{
		return true;
	}

	return false;
}
